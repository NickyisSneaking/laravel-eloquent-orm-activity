<?php

namespace Database\Factories;

use App\Models\Product;
use Illuminate\Database\Eloquent\Factories\Factory;
use Illuminate\Support\Str;
use App\Models\Category;

/**
 * @extends Factory<Product>
 */
class ProductFactory extends Factory
{
    /**
     * Define the model's default state.
     *
     * @return array<string, mixed>
     */
    public function definition(): array
    {
        //products and categories for the factory
        $categories = ['Hardware', 'Electrical', 'Plumbing'];
        $products =[
            ['category' => $categories[0], 'name' => 'hammer', 'price' => 250],
            ['category' => $categories[0], 'name' => 'screwdriver', 'price' => 150],
            ['category' => $categories[0], 'name' => 'wrench', 'price' => 200],
            ['category' => $categories[1], 'name' => 'light bulb', 'price' => 100],
            ['category' => $categories[1], 'name' => 'extension cord', 'price' => 300],
            ['category' => $categories[1], 'name' => 'switch', 'price' => 50],
            ['category' => $categories[2], 'name' => 'pipe wrench', 'price' => 400],
            ['category' => $categories[2], 'name' => 'plunger', 'price' => 80],
            ['category' => $categories[2], 'name' => 'faucet', 'price' => 500],
        ];
        $product = $this->faker->randomElement($products);

        //this code breaks now it is been fixed about 2 hours ago, the problem was that the name was not being formatted correctly, it was being formatted as "Hammer" instead of "hammer", this is because the name was being formatted as ucwords(strtolower(trim($product['name']))) which was causing the first letter to be capitalized, now it is been fixed to be formatted as ucwords(strtolower(trim($product['name']))) which will format the name correctly as "hammer" instead of "Hammer"
        $name = ucwords(strtolower(trim($product['name'])));

        //what is the purpose of this code? this code is used to generate a random product from the products array and return it as an array with the name, slug, category, price, quantity and status. The slug is generated by using the Str::slug() method which will convert the name to a URL friendly format and append a random number between 1000 and 9999 to ensure that the slug is unique. The quantity is generated by using the faker library to generate a random number between 1 and 100. The status is generated by using the faker library to randomly select one of the three statuses: Available, Out of Stock or Discontinued.
        return [
        'category_id' => Category::factory(),
        'name' => $name,
        'slug' => Str::slug($name) . '-' . $this->faker->unique()->numberBetween(1000, 9999), //ensures unique slugs by appending a random suffix number
        'price' => $product['price'],
        'description' => $this->faker->sentence(),
        'quantity' => $this->faker->numberBetween(1, 100),
        'status' => $this->faker->randomElement(['Available', 'Out of Stock',
        'Discontinued']), //shows product if available or not or discontuined
        ]; 
    }
}
